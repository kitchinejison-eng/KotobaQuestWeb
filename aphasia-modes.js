function startClearModeMic(status, trigger, onTranscript){
 var Rec=window.SpeechRecognition||window.webkitSpeechRecognition;
 if(!Rec){
  status.textContent='このブラウザは音声認識に対応していません。パソコンではGoogle ChromeまたはMicrosoft Edgeで開いてください。';
  return;
 }
 if(!window.AndroidSpeech && !window.isSecureContext && location.hostname!=='localhost' && location.hostname!=='127.0.0.1'){
  status.textContent='マイクを使うには、安全な接続（https://）でこのページを開いてください。';
  return;
 }
 if(modeSpeechRecognition){
  var oldRec=modeSpeechRecognition; modeSpeechRecognition=null;
  try{oldRec.onresult=null;oldRec.onerror=null;oldRec.onend=null;oldRec.abort();}catch(e){}
 }
 if(typeof speechRecognition!=='undefined') speechRecognition=null;
 var rec;
 var finalParts=[];
 var alternatives=[];
 var latestInterim='';
 var failure='';
 var originalLabel=trigger.getAttribute('data-mic-original-label')||trigger.textContent;
 trigger.setAttribute('data-mic-original-label',originalLabel);
 try{
  rec=new Rec(); modeSpeechRecognition=rec;
  if(typeof speechRecognition!=='undefined') speechRecognition=rec;
  rec.lang='ja-JP';
  rec.continuous=false;
  rec.interimResults=true;
  try{rec.maxAlternatives=5;}catch(e){}
  trigger.disabled=true;
  trigger.textContent='🎤　マイク準備中…';
  status.textContent='マイクを準備しています。許可を求められたら「許可」を押してください。';
  rec.onstart=function(){
   trigger.textContent='🔴　聞き取り中…';
   trigger.classList.add('is-listening');
   status.textContent='聞いています。絵の名前を、ひとこと声に出してください。';
  };
  rec.onresult=function(event){
   var interimParts=[];
   for(var i=0;i<event.results.length;i++){
    var result=event.results[i];
    if(!result || !result[0]) continue;
    if(result.isFinal){
     finalParts[i]=String(result[0].transcript||'').trim();
     // 認識候補も保存し、漢字・かなの表記揺れや音声認識の候補差に対応します。
     if(i===0){
      alternatives=[];
      for(var j=0;j<result.length;j++){
       var alt=String((result[j]&&result[j].transcript)||'').trim();
       if(alt && alternatives.indexOf(alt)<0) alternatives.push(alt);
      }
     }
    }else{
     var interim=String(result[0].transcript||'').trim();
     if(interim) interimParts.push(interim);
    }
   }
   latestInterim=interimParts.join('');
   var finalized=finalParts.filter(Boolean).join('').trim();
   if(finalized) status.textContent='聞き取りました：「'+finalized+'」　判定しています…';
   else if(latestInterim) status.textContent='聞き取り中：「'+latestInterim+'」';
  };
  rec.onerror=function(event){
   var code=event&&event.error?event.error:'';
   if(code==='not-allowed' || code==='service-not-allowed') failure='マイクの使用が許可されていません。アドレスバーのマイク設定を「許可」にして、もう一度押してください。';
   else if(code==='no-speech') failure='声を検出できませんでした。マイクの近くで、絵の名前をひとこと話してみてください。';
   else if(code==='audio-capture') failure='マイクが見つかりません。パソコンやタブレットのマイク設定を確認してください。';
   else if(code==='network') failure='音声認識サービスに接続できませんでした。インターネット接続を確認して、もう一度お試しください。';
   else if(code==='aborted') failure='聞き取りを中止しました。もう一度マイクを押してください。';
   else failure='音声を認識できませんでした。もう一度マイクを押して、ゆっくり話してください。';
   trigger.disabled=false;
   trigger.textContent=originalLabel;
   trigger.classList.remove('is-listening');
   status.textContent=failure;
  };
  rec.onend=function(){
   trigger.disabled=false;
   trigger.textContent=originalLabel;
   trigger.classList.remove('is-listening');
   if(modeSpeechRecognition===rec) modeSpeechRecognition=null;
   if(typeof speechRecognition!=='undefined' && speechRecognition===rec) speechRecognition=null;
   var transcript=finalParts.filter(Boolean).join('').trim();
   if(!transcript && latestInterim) transcript=latestInterim.trim();
   if(transcript && !failure){
    var candidates=alternatives.slice();
    if(candidates.indexOf(transcript)<0) candidates.unshift(transcript);
    status.textContent='聞き取りました：「'+transcript+'」　判定しています…';
    if(onTranscript) onTranscript(transcript,candidates);
   }else{
    status.textContent=failure||'声を検出できませんでした。マイクを押して、もう一度話してください。';
   }
  };
  rec.start();
 }catch(e){
  trigger.disabled=false;
  trigger.textContent=originalLabel;
  trigger.classList.remove('is-listening');
  if(modeSpeechRecognition===rec) modeSpeechRecognition=null;
  status.textContent='マイクを開始できませんでした。ページをhttps://で開き、ブラウザのマイク使用を許可してください。';
 }
}
